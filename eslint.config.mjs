import { FlatCompat } from '@eslint/eslintrc'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))

// eslint-config-next still ships the legacy (.eslintrc) format, so it is
// bridged into flat config here rather than replacing the shared Next rules
// with a home-grown approximation of them.
const compat = new FlatCompat({ baseDirectory: __dirname })

/**
 * This repo never had a committed lint config, so `next lint` could only ever
 * run interactively (it prompts to create one). The script now calls eslint
 * directly against this file — a lint run in CI or in a report has no one to
 * answer its questions.
 */
export default [
  {
    ignores: [
      'node_modules/**',
      '.next/**',
      '.next-dev/**',
      'public/**',
      'backups/**',
      'test-artifacts/**',
      '.scratch/**',
      // Third-party bundles and generated parity fixtures: not this repo's
      // source, and not something a lint rule can meaningfully change.
      'scripts/parity/.generated/**',
      // Generated by `next build`/`next dev`; its triple-slash reference is
      // Next's own output and is rewritten every run.
      'next-env.d.ts',
      // Root-level one-off diagnostics (inspect_db.js, verify_parity.js),
      // CommonJS by design and outside the app's module system.
      'inspect_db.js',
      'verify_parity.js',
      'prisma/dev.db',
      '*.config.js',
    ],
  },
  // Flat config only lints files some config explicitly claims, so the scope
  // is stated once here and inherited by every rule below.
  ...compat
    .extends('next/core-web-vitals', 'next/typescript')
    .map((config) => ({ ...config, files: ['**/*.{js,mjs,ts,tsx}'] })),
  {
    files: ['**/*.{ts,tsx}'],
    rules: {
      // The codebase passes data through loosely typed JSON boundaries
      // everywhere; turning this on is a refactor, not a lint fix.
      '@typescript-eslint/no-explicit-any': 'off',
      // `catch {}` with a comment is the house style for expected failures.
      '@typescript-eslint/no-unused-vars': [
        'error',
        {
          argsIgnorePattern: '^_',
          varsIgnorePattern: '^_',
          caughtErrorsIgnorePattern: '^_',
          ignoreRestSiblings: true,
        },
      ],
      // React 19 / Next 15 hoist the rules this came from into the runtime.
      'react-hooks/exhaustive-deps': 'warn',
      '@next/next/no-img-element': 'warn',
    },
  },
  {
    // Tailwind's config is loaded through a CJS loader, where `require()` is
    // the documented way to pull in plugins; rewriting it as an import risks
    // a default/namespace interop bug that only shows up as missing styles.
    files: ['tailwind.config.ts'],
    rules: {
      '@typescript-eslint/no-require-imports': 'off',
    },
  },
]
